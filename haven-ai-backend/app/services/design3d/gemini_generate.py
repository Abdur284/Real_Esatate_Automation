"""
Gemini-driven text -> 3D generation for the 3D Design module.

Selected with DESIGN3D_TEXT_GENERATOR=gemini. Gemini produces the 2D floor
plan (the 2D Design module, validated by design2d/validator.py), and the
deterministic 2D -> 3D converter then builds the geometry. So the layout is
AI-generated while the 3D geometry is always validated and reconstructed, not
emitted by the model. An unfeasible or underspecified request comes back as a
status for the user, never as an exception.
"""
import logging
from typing import Any, Dict, Optional

from app.services.design2d.service import Design2DError, generate_2d_plan

from .from_plan2d import generate_3d_from_plan2d
from .layout import MAX_STOREYS

logger = logging.getLogger(__name__)


def _needs_dimensions(missing) -> bool:
    keys = ("dimension", "width", "length", "plot size", "size")
    return any(any(k in str(m).lower() for k in keys) for m in missing or [])


async def generate_3d_from_prompt(
    prompt: str,
    plot_width_ft: Optional[float] = None,
    plot_length_ft: Optional[float] = None,
    storeys: Optional[int] = None,
) -> Dict[str, Any]:
    """prompt (+ optional plot size/storeys) -> Gemini 2D plan -> 3D model.
    Returns the same result shape as service.generate_3d_model."""
    floors: Optional[int] = None
    if storeys is not None:
        try:
            floors = max(1, min(int(storeys), MAX_STOREYS))
        except (TypeError, ValueError):
            floors = None

    try:
        plan = await generate_2d_plan(prompt, plot_width_ft, plot_length_ft, floors)
    except Design2DError as exc:
        logger.info("Gemini 3D generation: 2D planning failed: %s", exc)
        return {"status": "ERROR",
                "message": "The AI could not generate a design from that request: " + str(exc)
                           + " Describe the plot size and the rooms you need, e.g. \"25x50 ft plot, "
                             "3 bedrooms, 2 bathrooms, kitchen, TV lounge, parking, double storey\"."}

    status = str(plan.get("status") or "").upper()
    analysis = plan.get("analysis") or {}
    if status == "INSUFFICIENT_INFORMATION":
        missing = analysis.get("missing_information") or []
        message = analysis.get("reason") or "More information is needed to generate the design."
        if missing:
            message += " Please provide: " + ", ".join(str(m) for m in missing) + "."
        return {"status": "MISSING_DIMENSIONS" if _needs_dimensions(missing) else "INSUFFICIENT_INFORMATION",
                "message": message, "plan_2d": plan}
    if status == "NOT_FEASIBLE":
        suggestions = [str(s) for s in analysis.get("suggestions") or []]
        return {"status": "NOT_FEASIBLE",
                "message": analysis.get("reason")
                           or "The requested design does not fit on this plot within two floors.",
                "suggestion": "; ".join(suggestions) or None,
                "plan_2d": plan}

    result = generate_3d_from_plan2d(plan)
    if result.get("status") == "FEASIBLE":
        result["generator"] = "gemini"
        result["plan_2d"] = plan
        result["message"] = ("Generated a 2D layout with Gemini and built it in 3D. "
                             + result.get("message", "")).strip()
        for note in ("The 2D layout was generated by Gemini from your description; room positions and "
                     "sizes are the AI's design, then built to scale and validated.",):
            result.setdefault("assumptions", []).insert(0, note)
    else:
        result.setdefault("plan_2d", plan)
    return result
