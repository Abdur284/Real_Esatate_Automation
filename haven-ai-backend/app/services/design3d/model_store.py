"""
Short-lived in-memory store for generated GLB files.

Models are served by an opaque random id (GET /api/design/3d/models/{id}.glb),
so no filesystem path is ever exposed and nothing is written to disk. The store
is bounded by count and age; an expired model is simply regenerated by the
client from its structured JSON.
"""
import re
import secrets
import threading
import time
from collections import OrderedDict
from typing import Optional, Tuple

MAX_MODELS = 64
TTL_SECONDS = 2 * 60 * 60
MODEL_ID_RE = re.compile(r"^[0-9a-f]{32}$")

_lock = threading.Lock()
_models: "OrderedDict[str, Tuple[float, bytes]]" = OrderedDict()


def _evict(now: float) -> None:
    for key in [k for k, (t, _) in _models.items() if now - t > TTL_SECONDS]:
        del _models[key]
    while len(_models) > MAX_MODELS:
        _models.popitem(last=False)


def put(data: bytes) -> str:
    model_id = secrets.token_hex(16)
    with _lock:
        now = time.time()
        _models[model_id] = (now, data)
        _evict(now)
    return model_id


def get(model_id: str) -> Optional[bytes]:
    if not MODEL_ID_RE.match(model_id or ""):
        return None
    with _lock:
        _evict(time.time())
        entry = _models.get(model_id)
        return entry[1] if entry else None
